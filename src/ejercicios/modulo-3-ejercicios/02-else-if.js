/*
🧠 EJERCICIO 2 — ELSE IF

🎯 Objetivo:
Evaluar múltiples condiciones.

📌 Instrucciones:
1. Declara una variable nota con valor 75.
2. Si la nota es >= 90 → imprime "Excelente"
3. Si la nota es >= 70 → imprime "Aprobado"
4. Si no → imprime "Reprobado"

✅ Resultado esperado:
Aprobado
*/

// ✍️ Escribe tu solución aquí 👇

var nota = 75;

if (nota >= 90) {
  console.log("Excelente");
} else if (nota >= 70) {
  console.log("Aprobado");
} else {
  console.log("Reprobado");
}
