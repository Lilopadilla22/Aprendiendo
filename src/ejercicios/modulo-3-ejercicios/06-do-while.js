/*
🧠 EJERCICIO 6 — DO WHILE

🎯 Objetivo:
Entender que el bloque se ejecuta al menos una vez.

📌 Instrucciones:
1. Declara una variable numero con valor 3.
2. Usa do while para imprimir hasta que llegue a 1.


✅ Resultado esperado:
3
2
1
*/

// ✍️ Escribe tu solución aquí 👇

var numero = 3;
do {
  console.log(numero);
  numero--;
} while (numero > 0);
